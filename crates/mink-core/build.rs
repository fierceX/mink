use std::env;
use std::fs;
use std::path::Path;

fn main() {
    println!("cargo::rerun-if-changed=skills/");

    let out_dir = env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("embedded_skills.rs");

    let skills_dir = Path::new("skills");
    let mut entries = Vec::new();

    if skills_dir.is_dir() {
        for entry in fs::read_dir(skills_dir).unwrap() {
            let entry = entry.unwrap();
            let path = entry.path();
            if !path.is_dir() {
                continue;
            }
            let skill_file = path.join("SKILL.md");
            if !skill_file.exists() {
                continue;
            }
            let name = path.file_name().unwrap().to_string_lossy().to_string();
            let content = fs::read_to_string(&skill_file).unwrap_or_default();

            // Parse YAML frontmatter for description (same subset the runtime
            // parser supports, including `>` / `|` block scalars).
            let description = extract_frontmatter_field(&content, "description:")
                .unwrap_or_else(|| format!("Skill: {name}"));

            entries.push((name, description, skill_file.display().to_string()));
        }
    }

    // Sort by name for deterministic output
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    // Generate Rust source
    let mut code = String::from(
        "// Auto-generated by build.rs — do not edit manually.\n\
         // To add a skill: create skills/<name>/SKILL.md and rebuild.\n\n",
    );

    code.push_str("pub fn all() -> Vec<Skill> {\n");
    code.push_str("    vec![\n");
    for (name, desc, _path) in &entries {
        let name_literal = escape_rust_string(name);
        let desc_literal = escape_rust_string(desc);
        code.push_str(&format!(
            "        Skill {{\n\
             name: \"{name_literal}\",\n\
             description: \"{desc_literal}\",\n\
             content: include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/skills/{name_literal}/SKILL.md\")),\n\
         }},\n"
        ));
    }
    code.push_str("    ]\n");
    code.push_str("}\n");

    // Generate find function
    code.push_str(
        "#[cfg(test)]\n\
         pub fn find(name: &str) -> Option<Skill> {\n\
         all().into_iter().find(|s| s.name == name)\n\
         }\n",
    );

    fs::write(&dest_path, &code).unwrap();
    println!(
        "cargo::warning=Generated embedded_skills.rs with {} skills",
        entries.len()
    );
}

fn extract_frontmatter_field(content: &str, field: &str) -> Option<String> {
    let mut lines = content.lines().peekable();
    if lines.next()?.trim() != "---" {
        return None;
    }
    loop {
        let line = lines.next()?;
        let trimmed = line.trim();
        if trimmed == "---" {
            return None;
        }
        let Some(value) = trimmed.strip_prefix(field) else {
            continue;
        };
        let value = value.trim();
        // Block scalars (`>` folded / `|` literal) are joined for the embedded
        // description; blank lines inside the block stay paragraph breaks.
        if value.starts_with('>') || value.starts_with('|') {
            let literal = value.starts_with('|');
            let mut body: Vec<String> = Vec::new();
            let mut pending_blanks = 0usize;
            while let Some(peek) = lines.peek() {
                let line = peek.trim_end_matches('\r');
                if line.trim().is_empty() {
                    pending_blanks += 1;
                    lines.next();
                    continue;
                }
                if !line.starts_with(' ') && !line.starts_with('\t') {
                    break;
                }
                for _ in 0..pending_blanks {
                    body.push(String::new());
                }
                pending_blanks = 0;
                body.push(lines.next().unwrap().trim().to_string());
            }
            let text = if literal {
                body.join("\n")
            } else {
                let mut out = String::new();
                let mut paragraph: Vec<&str> = Vec::new();
                for line in &body {
                    if line.is_empty() {
                        if !paragraph.is_empty() {
                            if !out.is_empty() {
                                out.push('\n');
                            }
                            out.push_str(&paragraph.join(" "));
                            paragraph.clear();
                        }
                    } else {
                        paragraph.push(line.as_str());
                    }
                }
                if !paragraph.is_empty() {
                    if !out.is_empty() {
                        out.push('\n');
                    }
                    out.push_str(&paragraph.join(" "));
                }
                out
            };
            let text = text.trim();
            return (!text.is_empty()).then(|| text.to_string());
        }
        let val = value.trim_matches('"').trim_matches('\'');
        if !val.is_empty() {
            return Some(val.to_string());
        }
    }
}

/// Escape a value for interpolation into a generated Rust string literal.
fn escape_rust_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(ch),
        }
    }
    out
}
